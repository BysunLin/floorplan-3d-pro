/* ============================================================================
 *  洞口竖向尺寸（单位 m）
 *
 *  这些数值同时被 2D 立面示意、3D 建墙与节点模型使用，
 *  统一放在 core 层，避免 view3d / stores 各写一份再对不上。
 * ========================================================================== */

/** 平开门洞上缘高度 */
export const DOOR_H = 2.1;

/** 推拉门上缘：竖向推拉（s.v）为 2.4m，横向为 2.1m */
export const SLIDE_HEAD_V = 2.4;

/** 窗洞上缘高度 */
export const WIN_HEAD = 2.4;

/** 推拉门洞口上缘（s.v 表示轨道竖向） */
export const slideHead = s => (s?.v ? SLIDE_HEAD_V : DOOR_H);

/**
 * 窗台高度（按户型静态几何的下标约定）：
 * 0 → 落地窗；6 及以后 → 飘窗（0.45m 台面）；其余 → 普通窗 0.9m
 */
export const winSill = i => (i === 0 ? 1.4 : i >= 6 ? .45 : .9);
