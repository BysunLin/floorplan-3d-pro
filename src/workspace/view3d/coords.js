/* ============================================================================
 *  平面坐标（mm）⇄ 世界坐标（m）换算
 *  户型中心 (6000, 5300) 放在世界原点，层高 2.8 m。
 * ========================================================================== */
export const OX = 6000, OY = 5300;
export const H = 2.8;      // 层高（米）
export const FOV = 45;

export const wx = x => (x - OX) / 1000;
export const wz = y => (y - OY) / 1000;
export const M  = v => v / 1000;
